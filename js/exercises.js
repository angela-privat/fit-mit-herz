/** Text für Dosierung, z. B. "10 Wiederholungen pro Seite" */
export function doseText(ex, level = 1) {
  const i = Math.max(0, Math.min(2, level - 1));
  const side = ex.sided ? ' pro Seite' : '';
  if (ex.dose.reps) return `${ex.dose.reps[i]} ruhige Wiederholungen${side}`;
  if (ex.dose.hold) return `${ex.dose.hold[i]} Sek. halten${side}`;
  return 'Gleichmäßig in deinem Tempo';
}
